#!/usr/bin/env bash
# gen-layer-triggers-upgrade.sh — print a layer's trigger upgrade file.
#
#   bash scripts/gen-layer-triggers-upgrade.sh <layer> > sql/<layer>/upgrades/triggers.sql
#
# Emits DROP TRIGGER IF EXISTS + the trigger file for every file under
# sql/<layer>/triggers/, under a fixed sql_mode, so an existing database gets
# exactly the triggers a fresh build has. A trigger removed from that
# directory keeps its DROP through RETIRED below.
#
# `make db-schema` writes the file and `make verify-codegen` fails on drift.
#
# Exit codes: 0 ok, 2 bad usage.

set -euo pipefail

# Byte-ordered globbing keeps the output identical across platforms.
export LC_ALL=C

SQL_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../sql" && pwd)"

# Triggers removed from a layer, as "<layer>:<trigger>".
RETIRED=()

# Recorded into every trigger it creates; matches the server default.
SQL_MODE="ONLY_FULL_GROUP_BY,STRICT_TRANS_TABLES,NO_ZERO_IN_DATE,NO_ZERO_DATE,ERROR_FOR_DIVISION_BY_ZERO,NO_ENGINE_SUBSTITUTION"

if [[ $# -ne 1 ]]; then
  echo "usage: gen-layer-triggers-upgrade.sh <layer>" >&2
  exit 2
fi
layer="$1"
case "${layer}" in
  *[!A-Za-z0-9_-]* | "" | core)
    echo "gen-layer-triggers-upgrade.sh: invalid layer: ${layer}" >&2
    exit 2
    ;;
esac
dir="${SQL_ROOT}/${layer}/triggers"
if [[ ! -d "${dir}" ]]; then
  echo "gen-layer-triggers-upgrade.sh: no such directory: ${dir}" >&2
  exit 2
fi

echo "-- Generated by scripts/gen-layer-triggers-upgrade.sh ${layer}"
echo "-- DO NOT EDIT; edit sql/${layer}/triggers/ and run make db-schema."
echo "--"
echo "-- Apply last, after every other upgrade, with the writers of both"
echo "-- products stopped: MySQL has no atomic trigger replace, so a delete"
echo "-- between a DROP and its CREATE runs without the trigger."
echo "SET NAMES utf8mb4;"
echo "SET SESSION sql_mode = '${SQL_MODE}';"
echo

for entry in ${RETIRED[@]+"${RETIRED[@]}"}; do
  if [[ "${entry%%:*}" == "${layer}" ]]; then
    echo "DROP TRIGGER IF EXISTS \`${entry#*:}\`;"
  fi
done

for f in "${dir}"/*.sql; do
  [[ -e "${f}" ]] || continue
  echo "-- >>> $(basename "${f}")"
  echo "DROP TRIGGER IF EXISTS \`$(basename "${f}" .sql)\`;"
  cat "${f}"
  echo
done
